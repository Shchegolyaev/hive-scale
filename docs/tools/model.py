"""Модель платформы весов: список параллелепипедов в миллиметрах.

Оси: X — влево/вправо, Y — назад (+) / вперёд (−), Z — вверх. Z=0 — верх щебёночной подушки.
Из этой модели строятся вид спереди, вид сверху (build_drawings.py) и 3D-рендер (render3d.html).
"""

# Цвета
WOOD = "#B9824A"
STEEL = "#8D99A6"
STEEL_D = "#4F5862"
ALU = "#C9CED4"
PLY = "#7A4E2D"
SLAB = "#B9B4AA"
GRAVEL = "#CFC8BA"
RUST = "#8B4A2B"
HIVE = "#F2D27A"
HIVE_D = "#E3BE5A"
ROOF = "#C9A445"
STRAP = "#E8701A"
WOOD_L = "#C69159"
BOX = "#E6E9EC"

# Ключевые размеры
DECK = 600            # настил 600×600 (предел платформы для L6G)
DECK_T = 27           # ламинированная фанера 27 мм — несёт улей без рёбер
LEG = 275             # оси ножек: квадрат 550×550, ножки под углами настила
SPIKE = 900           # пика забивной опоры
CUP = 150             # высота стакана опоры над землёй
LEG_DOWN = SPIKE
SPACER = 10           # стальная проставка
CELL_L, CELL_W, CELL_H = 174, 65, 60   # Zemic L6G 300 кг, по паспорту; сверь со своим
BOARD = 50            # доска 50×100 плашмя: 100 шириной, 50 высотой
BOARD_W = 100
STOP_GAP = 3          # зазор стоп-болтов (дерево «дышит» — больше, чем у стали)

z_frame0 = CUP + 10                            # 160 — низ лежней: на 1 см выше стакана опоры
z_sleeper = z_frame0 + 100                     # 260 — верх лежней (доска 50×100 на ребро)
z_lt = z_frame0 + BOARD                        # 210 — верх средней поперечины
z_cell0 = z_lt + SPACER                        # 220
z_cell1 = z_cell0 + CELL_H                     # 280
z_deck = z_cell1 + DECK_T                      # 307 — настил прямо на датчике
z_leg = z_cell1 - 20                           # 260 — вровень с верхом лежней; в торце — стоп-шпилька

HIVE_X, HIVE_Y = 550, 550   # габарит улья по дну и крыше (Нижегородец, реальные размеры)

boxes = []


def box(name, x0, x1, y0, y1, z0, z1, color, group="base", num=None):
    boxes.append(dict(name=name, x0=x0, x1=x1, y0=y0, y1=y1, z0=z0, z1=z1,
                      color=color, group=group, num=num))


# Грунт
box("Грунт", -600, 600, -600, 600, -SPIKE - 100, 0, GRAVEL, "ground")

# 1. Забивные опоры и ножки — брус 100×100 в стакане опоры, дерево не касается земли
for sx in (-1, 1):
    for sy in (-1, 1):
        x, y = sx * LEG, sy * LEG
        box("Забивная опора 100×100: пика", x - 20, x + 20, y - 20, y + 20, -SPIKE, 0, STEEL, "base", 9)
        box("Забивная опора 100×100: пластина", x - 58, x + 58, y - 58, y + 58, 0, 3, STEEL, "base", 9)
        for (a0, a1, b0, b1) in ((-52, -50, -52, 52), (50, 52, -52, 52), (-50, 50, -52, -50), (-50, 50, 50, 52)):
            box("Забивная опора 100×100: стакан", x + a0, x + a1, y + b0, y + b1, 3, CUP, STEEL, "base", 9)
        box("Ножка: брус 100×100", x - 50, x + 50, y - 50, y + 50, 3, z_leg, WOOD, "base", 1)

# 2. Лежни — доска 50×100 на ребро, на внутренних гранях ножек
for sx in (-1, 1):
    l0, l1 = sorted((sx * (LEG - 100), sx * (LEG - 50)))
    box("Лежень: доска 50×100×650", l0, l1, -LEG - 50, LEG + 50, z_frame0, z_sleeper, WOOD_L, "base", 2)

# 3. Средняя поперечина — доска 50×100 плашмя между лежнями
box("Средняя поперечина: доска 50×100×350 плашмя", -(LEG - 100), LEG - 100, -BOARD_W / 2, BOARD_W / 2, z_frame0, z_lt, WOOD, "base", 3)

# 4–5. Датчик и проставки
box("Проставка, сталь 10 мм (неподвижный конец)", -CELL_L / 2, -CELL_L / 2 + 80, -CELL_W / 2, CELL_W / 2, z_lt, z_cell0, STEEL_D, "base", 4)
box("Датчик L6G 300 кг", -CELL_L / 2, CELL_L / 2, -CELL_W / 2, CELL_W / 2, z_cell0, z_cell1, ALU, "cell", 5)
# 6. Настил — прямо на датчике, как в промышленных платформенных весах
box("Настил: ламинированная фанера 27 мм, 600×600", -DECK / 2, DECK / 2, -DECK / 2, DECK / 2, z_cell1, z_deck, PLY, "deck", 6)

# 8. Стоп-болты в торцах ножек
for sx in (-1, 1):
    for sy in (-1, 1):
        x, y = sx * LEG, sy * LEG
        box("Стоп-болт: шуруп-шпилька М10", x - 5, x + 5, y - 5, y + 5, z_leg, z_deck - STOP_GAP - 8, STEEL_D, "base", 7)
        box("Стоп-болт: гайка", x - 9, x + 9, y - 9, y + 9, z_deck - STOP_GAP - 8, z_deck - STOP_GAP, "#3A424A", "base", 7)

# 9. Коробка электроники — на наружной грани задней правой ножки (неподвижная часть)
box("Корпус электроники IP65", LEG - 60, LEG + 90, LEG + 50, LEG + 120, CUP + 10, CUP + 110, BOX, "base", 8)

# Улей «Нижегородец» из ППУ (beelekar.ru), реальные размеры:
# дно 550×550×120, корпус 520×520×310, магазин 520×520×160, крыша 550×550×100
BODY = 520
LID = 550
z = z_deck
box("Дно: ППУ 550×550×120", -LID / 2, LID / 2, -LID / 2, LID / 2, z, z + 120, HIVE_D, "hive"); z += 120
box("Корпус: ППУ 520×520×310", -BODY / 2, BODY / 2, -BODY / 2, BODY / 2, z, z + 310, HIVE, "hive"); z += 310
box("Корпус: ППУ 520×520×310", -BODY / 2, BODY / 2, -BODY / 2, BODY / 2, z, z + 310, HIVE, "hive"); z += 310
box("Магазин: ППУ 520×520×160", -BODY / 2, BODY / 2, -BODY / 2, BODY / 2, z, z + 160, HIVE, "hive"); z += 160
box("Крыша: ППУ 550×550×100", -LID / 2, LID / 2, -LID / 2, LID / 2, z, z + 100, ROOF, "hive"); z_top = z + 100

# Ремень — самозатягивающийся крюк-болт (50 мм): крюки за стоп-шпильки передней и
# задней ножек, полотно по кромке крыши. Улей держится за раму: датчик видит только прижим.
SW = 50                                  # ширина ленты
sx0, sx1 = LID / 2 - SW / 2, LID / 2 + SW / 2   # полотно по правой кромке крыши: x 250..300
box("Ремень крюк-болт: полотно по кромке крыши", sx0, sx1, -LID / 2 - 4, LID / 2 + 4, z_top, z_top + 3, STRAP, "strap")
box("Ремень: ветвь к передней шпильке", sx0, sx1, -LID / 2 - 4, -LID / 2, 245, z_top, STRAP, "strap")
box("Ремень: ветвь к задней шпильке", sx0, sx1, LID / 2, LID / 2 + 4, 245, z_top, STRAP, "strap")
box("Крюк ремня за стоп-шпильку (передняя)", LID / 2 - 8, LID / 2 + 8, -LID / 2 - 8, -LID / 2 + 8, 243, 267, STEEL_D, "strap")
box("Крюк ремня за стоп-шпильку (задняя)", LID / 2 - 8, LID / 2 + 8, LID / 2 - 8, LID / 2 + 8, 243, 267, STEEL_D, "strap")
box("Механизм натяжения ремня", LID / 2 - SW / 2 + 4, LID / 2 + SW / 2 - 4, LID / 2 + 4, LID / 2 + 13, 560, 640, "#3A424A", "strap")

HEIGHT_TOP = z_top
